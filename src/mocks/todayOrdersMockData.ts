let mockOrdersState = [...MOCK_TODAY_ORDERS];

export function getMockTodayOrders(): TodayOrder[] {
  return [...mockOrdersState];
}

export function updateMockOrder(updated: TodayOrder): TodayOrder {
  mockOrdersState = mockOrdersState.map((order) =>
    order._id === updated._id ? {...order, ...updated} : order,
  );
  return mockOrdersState.find((o) => o._id === updated._id) ?? updated;
}

export function resetMockTodayOrders(): void {
  mockOrdersState = [...MOCK_TODAY_ORDERS];
}
